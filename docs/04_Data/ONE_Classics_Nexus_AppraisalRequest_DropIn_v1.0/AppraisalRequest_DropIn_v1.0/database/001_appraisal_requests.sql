CREATE TABLE IF NOT EXISTS appraisal_request_sequences (
 sequence_year INT NOT NULL PRIMARY KEY,
 last_value BIGINT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS appraisal_requests (
 appraisal_request_id CHAR(36) NOT NULL,
 request_number VARCHAR(30) NOT NULL,
 client_id CHAR(36) NOT NULL,
 client_contact_id CHAR(36) NULL,
 vehicle_id CHAR(36) NULL,
 converted_appraisal_id CHAR(36) NULL,
 request_status VARCHAR(30) NOT NULL,
 request_source VARCHAR(50) NULL,
 requested_appraisal_type VARCHAR(100) NOT NULL,
 requested_purpose VARCHAR(255) NOT NULL,
 requested_intended_use LONGTEXT NULL,
 requested_value_type VARCHAR(100) NULL,
 requested_effective_date DATE NULL,
 requested_completion_date DATE NULL,
 inspection_preference VARCHAR(50) NULL,
 inspection_location VARCHAR(500) NULL,
 subject_year SMALLINT NULL,
 subject_make VARCHAR(100) NULL,
 subject_model VARCHAR(100) NULL,
 subject_vin VARCHAR(50) NULL,
 subject_description LONGTEXT NULL,
 client_comments LONGTEXT NULL,
 internal_notes LONGTEXT NULL,
 requester_acknowledged_verification BOOLEAN NOT NULL DEFAULT 0,
 qualification_status VARCHAR(30) NOT NULL,
 qualification_notes LONGTEXT NULL,
 assigned_to_user_id CHAR(36) NULL,
 qualified_by_user_id CHAR(36) NULL,
 received_at_utc DATETIME(6) NOT NULL,
 reviewed_at_utc DATETIME(6) NULL,
 qualified_at_utc DATETIME(6) NULL,
 converted_at_utc DATETIME(6) NULL,
 closed_at_utc DATETIME(6) NULL,
 row_version BIGINT NOT NULL DEFAULT 1,
 created_at_utc DATETIME(6) NOT NULL,
 updated_at_utc DATETIME(6) NOT NULL,
 PRIMARY KEY(appraisal_request_id),
 UNIQUE KEY uq_appraisal_requests_number(request_number),
 UNIQUE KEY uq_appraisal_requests_converted_appraisal(converted_appraisal_id),
 KEY ix_appraisal_requests_client(client_id),
 KEY ix_appraisal_requests_status(request_status),
 KEY ix_appraisal_requests_assignee_status(assigned_to_user_id,request_status),
 KEY ix_appraisal_requests_vehicle(vehicle_id),
 KEY ix_appraisal_requests_received(received_at_utc),
 CONSTRAINT fk_ar_client FOREIGN KEY(client_id) REFERENCES clients(client_id) ON DELETE RESTRICT,
 CONSTRAINT fk_ar_client_contact FOREIGN KEY(client_contact_id) REFERENCES client_contacts(client_contact_id) ON DELETE SET NULL,
 CONSTRAINT fk_ar_vehicle FOREIGN KEY(vehicle_id) REFERENCES vehicles(vehicle_id) ON DELETE SET NULL,
 CONSTRAINT fk_ar_converted_appraisal FOREIGN KEY(converted_appraisal_id) REFERENCES appraisals(appraisal_id) ON DELETE RESTRICT,
 CONSTRAINT fk_ar_assigned_user FOREIGN KEY(assigned_to_user_id) REFERENCES users(user_id) ON DELETE SET NULL,
 CONSTRAINT fk_ar_qualified_user FOREIGN KEY(qualified_by_user_id) REFERENCES users(user_id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS appraisal_request_audit (
 appraisal_request_audit_id CHAR(36) NOT NULL PRIMARY KEY,
 appraisal_request_id CHAR(36) NOT NULL,
 actor_user_id CHAR(36) NULL,
 occurred_at_utc DATETIME(6) NOT NULL,
 action VARCHAR(80) NOT NULL,
 prior_status VARCHAR(30) NULL,
 new_status VARCHAR(30) NOT NULL,
 reason LONGTEXT NULL,
 correlation_id VARCHAR(100) NULL,
 appraisal_id CHAR(36) NULL,
 KEY ix_ar_audit_request_time(appraisal_request_id,occurred_at_utc),
 CONSTRAINT fk_ar_audit_request FOREIGN KEY(appraisal_request_id) REFERENCES appraisal_requests(appraisal_request_id) ON DELETE RESTRICT
) ENGINE=InnoDB;
